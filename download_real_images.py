def fetch_image_url(query):
    try:
        url = "https://ru.wikipedia.org/w/api.php?action=query&titles=" + urllib.parse.quote(query) + "&prop=pageimages&format=json&pithumbsize=800"
        req = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(req, context=ctx, timeout=10) as resp:
            data = json.loads(resp.read().decode('utf-8'))
            pages = data.get('query', {}).get('pages', {})
            for pid in pages:
                thumb = pages[pid].get('thumbnail', {})
                if 'source' in thumb:
                    return thumb['source']
    except Exception as e:
        print(f"Error fetching {query}: {e}")
    return None

def download_image(url, filepath):
    try:
        req = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(req, context=ctx, timeout=15) as resp:
            with open(filepath, 'wb') as f:
                f.write(resp.read())
        return True
    except Exception as e:
        print(f"Download failed for {url}: {e}")
        return False

out_dir = "/Users/emir/Документы/заметки обсидиан/presentation/images"
os.makedirs(out_dir, exist_ok=True)

downloaded_map = {}

# Fallback default image in case any fail
fallback_path = None

print("Starting image download for 100 slides...")

for i, item in enumerate(TOPICS):
    slide_num = i + 1
    fname = f"slide_{slide_num:03d}.jpg"
    target_path = os.path.join(out_dir, fname)
    rel_path = f"images/{fname}"
    
    if os.path.exists(target_path) and os.path.getsize(target_path) > 5000:
        print(f"[{slide_num}/100] Already exists: {fname}")
        downloaded_map[i] = {"path": rel_path, "caption": item["caption"]}
        if not fallback_path:
            fallback_path = target_path
        continue
    
    img_url = fetch_image_url(item["title"])
    success = False
    if img_url:
        success = download_image(img_url, target_path)
    
    if success and os.path.getsize(target_path) > 5000:
        print(f"[{slide_num}/100] Downloaded for '{item['title']}' -> {fname}")
        downloaded_map[i] = {"path": rel_path, "caption": item["caption"]}
        if not fallback_path:
            fallback_path = target_path
    else:
        # Fallback query
        print(f"[{slide_num}/100] Retrying with generic term for '{item['title']}'...")
        alt_url = fetch_image_url("Серебряный век русской поэзии") or fetch_image_url("Блок, Александр Александрович")
        if alt_url and download_image(alt_url, target_path):
            downloaded_map[i] = {"path": rel_path, "caption": item["caption"]}
        elif fallback_path and os.path.exists(fallback_path):
            import shutil
            shutil.copy(fallback_path, target_path)
            downloaded_map[i] = {"path": rel_path, "caption": item["caption"]}
        else:
            downloaded_map[i] = {"path": rel_path, "caption": item["caption"]}
    
    time.sleep(0.1)

# Now write map to json
with open("/Users/emir/Документы/заметки обсидиан/presentation/images_map.json", "w", encoding="utf-8") as f:
    json.dump(downloaded_map, f, ensure_ascii=False, indent=2)

print("Finished downloading images! Total mapped:", len(downloaded_map))
